def write(tokens_json: Path, out: Path) -> Path:
    """Write `<out>/ds/commise/native.css` from the canvas's `tokens.json`."""
    tokens = json.loads(tokens_json.read_text())
    chrome = json.loads((HERE / "chrome.json").read_text())
    path = out / "ds/commise/native.css"
    path.write_text(native_css(tokens, chrome))
    return path
