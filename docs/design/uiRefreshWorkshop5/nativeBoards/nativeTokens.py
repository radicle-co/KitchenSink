"""Write `native.css`, the native boards' shared stylesheet, from the design system's own sources.

Colours and type come from the canvas's `ds/commise/tokens.json` (the same roles Tamagui's themes are built from:
`tamaguiThemes.ts` spreads `role` and `roleDark`). Side spacing is 16 everywhere (owner ruling T31), with any cited
platform exception in `chrome.json`. The tab bar and home indicator sizes come from `chrome.json`, which cites the component each one is
copied from. The colour values themselves stay in `tokens.css` (`--ink`, `--paper-raised` and the rest), which every
board already links, so this file only names roles and never restates a hex value.
"""

import json
import re
from pathlib import Path

HERE = Path(__file__).resolve().parent


def side_spacing(device: dict, context: str, rule: dict | None = None) -> int:
    """The side padding for a screen or a sheet on a device (owner ruling T31, 2026-11-01): 16 everywhere, unless a
    platform guideline sets a value for that exact context. An exception must cite its source, or the build stops."""
    rule = json.loads((HERE / "chrome.json").read_text())["sideSpacing"] if rule is None else rule
    for exception in rule["exceptions"]:
        if not exception.get("source"):
            raise SystemExit(f"side-spacing exception {exception} has no source; T31 allows only cited exceptions")
        if (exception["os"], exception["kind"], exception["context"]) == (device["os"], device["kind"], context):
            return int(exception["value"])
    return int(rule["default"])


def type_role(tokens: dict, name: str) -> dict:
    for group in tokens["type"]["groups"]:
        for style in group["styles"]:
            if style["name"] == name:
                return {**style, "family": group["family"]}
    raise SystemExit(f"tokens.json has no type role `{name}`")


