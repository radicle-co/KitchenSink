/**
 * `npm run local:up` — stand up every piece of infrastructure this repo declares, locally.
 *
 * ⛔ EVERYTHING HERE IS DERIVED FROM `cdk synth`. Nothing about which services, which containers, which
 * databases or which buckets is written down in this package. That is the whole point: a queue, bucket,
 * table or database added to the CDK tomorrow is stood up by this command the same day, with nothing to
 * remember and nothing to edit outside the CDK.
 *
 * It replaces two hand-maintained compose files that had already drifted apart and could not both run —
 * `docker-compose.yml` (LocalStack 3, `SERVICES: s3`) and `infra/localstack/docker-compose.yml`
 * (LocalStack 4.4.0, everything except s3). Both bind 5432 and 4566.
 *
 * @sideEffect Spawns CDK and docker, writes generated files under `.local-sandbox/`, and starts containers.
 */
import { spawnSync } from 'node:child_process';
import { existsSync, mkdirSync, mkdtempSync, readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import path from 'node:path';

import { discoverApps } from '../src/discoverApps.js';
import { discoverResources, summarizeRequirements, type DiscoveredResource } from '../src/discoverResources.js';
import { planCompose } from '../src/composePlan.js';
import { discoverDatabases, discoverMigrations, discoverServiceTasks, resolveExports } from '../src/runPlan.js';
import { discoverImageBuilds, localContainerEnv, portConflicts } from '../src/localImages.js';
import { secretRefsOf, ssmRefsOf } from '../src/secretRefs.js';
import { MIGRATION_TABLE, pendingMigrations } from '../src/pendingMigrations.js';
import {
    creatableResources,
    importRefsOf,
    localExportMap,
    ownRefsOf,
    resolveImport,
    resolveParameterValues,
    type CreatableResource,
} from '../src/awsResources.js';
import type { ServiceContainer } from '../src/composePlan.js';
import { synthesizeAll } from '../src/synthesize.js';
import {
    REPO_ROOT,
    buildServiceImage,
    fetchSecret,
    fetchSsmParameter,
    createLocalResource,
    localPortFor,
    readManifests,
    runCdkSynth,
} from './adapters.js';

const GENERATED_DIR = path.join(REPO_ROOT, '.local-sandbox');

/** Serialise the plan as compose YAML. Hand-rolled because the shape is small, fixed and fully ours. */
function toYaml(plan: ReturnType<typeof planCompose>): string {
    const lines = [
        '# GENERATED by `npm run local:up` from the synthesised CDK. Do not edit — regenerate.',
        '',
        'services:',
    ];

    for (const [name, service] of Object.entries(plan.services)) {
        if (service === undefined) {
            continue;
        }

        lines.push(
            `    ${name}:`,
            `        image: ${service.image}`,
            `        container_name: local-sandbox-${name}`,
            '        restart: unless-stopped',
            '        ports:',
            ...service.ports.map((port) => `            - '${port}'`),
            '        environment:',
            ...Object.entries(service.environment).map(([key, value]) => `            ${key}: '${value}'`),
            '        healthcheck:',
            `            test: ${JSON.stringify((service.healthcheck as { test: string[] }).test)}`,
            `            interval: ${String((service.healthcheck as { interval: string }).interval)}`,
            `            timeout: ${String((service.healthcheck as { timeout: string }).timeout)}`,
            `            retries: ${String((service.healthcheck as { retries: number }).retries)}`,
        );

        if (service.dependsOn !== undefined) {
            lines.push(
                '        depends_on:',
                ...service.dependsOn.flatMap((dep) => [
                    `            ${dep}:`,
                    '                condition: service_healthy',
                ]),
            );
        }

        if (service.volumes !== undefined) {
            lines.push('        volumes:', ...service.volumes.map((volume) => `            - ${volume}`));
        }

        if (name === 'postgres') {
            lines.push('            - ./init.sql:/docker-entrypoint-initdb.d/init.sql:ro');
        }
    }

    lines.push('', 'volumes:', '    local-sandbox-pgdata:', '');

    return lines.join('\n');
}

async function main(): Promise<void> {
    const apps = discoverApps(readManifests());

    process.stdout.write(`Synthesising ${apps.length} CDK app(s) — this is the only source of truth…\n`);

    const outcomes = await synthesizeAll(apps, runCdkSynth, {
        outRoot: mkdtempSync(path.join(tmpdir(), 'local-sandbox-')),
    });
    const broken = outcomes.filter((outcome) => !outcome.usable);

    // ⛔ A hole in the inventory is indistinguishable from "that infrastructure does not exist", which is
    // exactly how the predecessor reported a repo with no database. Refuse rather than start something
    // partial and call it "everything".
    if (broken.length > 0) {
        process.stderr.write('\nRefusing to start: these apps did not synthesise, so the inventory is INCOMPLETE.\n');

        for (const outcome of broken) {
            process.stderr.write(
                `  ${outcome.app.packageName}\n${outcome.stderr
                    .trim()
                    .split('\n')
                    .slice(-4)
                    .map((l) => `      ${l}`)
                    .join('\n')}\n`,
            );
        }

        process.exitCode = 1;

        return;
    }

    const templates = outcomes.flatMap((outcome) => outcome.templates);
    const resources: DiscoveredResource[] = templates.flatMap((file) => [
        ...discoverResources(
            path.basename(file).replace(/\.template\.json$/u, ''),
            JSON.parse(readFileSync(file, 'utf8')),
        ),
    ]);
    const requirements = summarizeRequirements(resources);

    if (requirements.undecided.length > 0) {
        process.stderr.write('\nRefusing to start: infrastructure with no local-support decision.\n');

        for (const type of requirements.undecided) {
            process.stderr.write(`  ${type}\n`);
        }

        process.stderr.write('Add each to LOCAL_SUPPORT in src/localSupport.ts, with a reason.\n');
        process.exitCode = 1;

        return;
    }

    // ⛔ Built across ALL templates before anything is resolved: `IdentityService` names its database as an
    // import of `kitchensink-data-{stage}:DatabaseName`, and only the GLOBAL Data stack declares the
    // literal. A per-stack view cannot see it, which is how identity's migrations were silently skipped.
    const parsedTemplates = templates.map((file) => JSON.parse(readFileSync(file, 'utf8')) as unknown);
    const exportMap = resolveExports(parsedTemplates);
    const databases = discoverDatabases(parsedTemplates, exportMap);
    // Env NAMES each stack's containers declare, so a locally-run image gets the same variables set.
    const tasksByStack = new Map<string, string[]>();

    for (const file of templates) {
        const stack = path.basename(file).replace(/\.template\.json$/u, '');
        const keys = discoverServiceTasks(stack, JSON.parse(readFileSync(file, 'utf8'))).flatMap((task) => [
            ...task.envKeys,
        ]);

        if (keys.length > 0) {
            tasksByStack.set(stack, [...new Set(keys)].sort());
        }
    }

    // ⛔ THE DECLARED AWS RESOURCES, AND THE NAMES THE CONTAINERS EXPECT THEM UNDER. LocalStack was being
    // started and never populated: every declared bucket, queue, table and topic was absent, so services ran
    // with `S3_BUCKET_PHOTOS=local-placeholder` and `ACCOUNT_ERASURE_QUEUE_URL=http://localhost:1`. Nothing
    // failed at startup — the endpoint and credentials were fine — so the first symptom would have been a
    // photo upload 500ing at run time.
    //
    // ⚠️ Resolved PURELY here, before anything is created: the names are derived from the templates and are
    // stable, so the compose file can be written with them and the resources created afterwards.
    const localStackTarget = { endpoint: 'http://localstack:4566', region: 'us-east-1', account: '000000000000' };
    const namedTemplates = templates.map((file) => ({
        stack: path.basename(file).replace(/\.template\.json$/u, ''),
        template: JSON.parse(readFileSync(file, 'utf8')) as unknown,
    }));
    const exportsLocally = localExportMap(namedTemplates, localStackTarget);
    const toCreate: readonly CreatableResource[] = resolveParameterValues(
        namedTemplates.flatMap((entry) => [...creatableResources(entry.stack, entry.template)]),
        localStackTarget,
    );
    // An SSM parameter this run creates is also the answer for any env var that reads it — and it is the
    // ONLY answer when the deployed stage does not exist in real AWS, which is the case for every
    // `/kitchensink/dev/` path here.
    const ssmLocally: Record<string, string> = {};

    for (const resource of toCreate) {
        const value = resource.properties['Value'];

        if (resource.type === 'AWS::SSM::Parameter' && typeof value === 'string' && value !== 'local-placeholder') {
            ssmLocally[resource.name] = value;
        }
    }

    const importsByStack = new Map<string, Record<string, string>>();

    for (const entry of namedTemplates) {
        // A stack that OWNS the resource references it directly; only another stack's resource goes through
        // an export. Both routes end at the same place.
        const own = ownRefsOf(entry.stack, entry.template, localStackTarget);

        if (Object.keys(own).length > 0) {
            importsByStack.set(entry.stack, { ...importsByStack.get(entry.stack), ...own });
        }

        for (const ref of importRefsOf(entry.template)) {
            const value = resolveImport(ref.exportName, exportsLocally);

            if (value !== undefined) {
                importsByStack.set(entry.stack, { ...importsByStack.get(entry.stack), [ref.name]: value });
            }
        }
    }

    // ⛔ SECRETS ARE PART OF THE ENVIRONMENT, and they are not in `Environment`. ECS injects them from
    // Secrets Manager at task start, so the template carries only a reference — which meant a container came
    // up missing exactly the variables its service is most likely to REQUIRE. `food-service` crash-looped on
    // its own zod schema for want of `USDA_API_KEY`, while the other two came up healthy: a local stack that
    // is two-thirds real reads as a working one.
    //
    // Resolved from AWS the way `.github/actions/load-secrets/action.yml` resolves the Clerk keys, so a local
    // run gets the value the pipeline gets. Each distinct secret is fetched ONCE — food declares
    // `USDA_API_KEY` on all three of its task definitions.
    const secretsByStack = new Map<string, Record<string, string>>();
    const secretCache = new Map<string, string | undefined>();
    const unresolved: string[] = [];

    for (const file of templates) {
        const stack = path.basename(file).replace(/\.template\.json$/u, '');
        const refs = secretRefsOf(JSON.parse(readFileSync(file, 'utf8')));

        for (const ref of refs) {
            const cacheKey = `${ref.secretId}#${ref.jsonKey ?? ''}`;

            if (!secretCache.has(cacheKey)) {
                secretCache.set(cacheKey, fetchSecret(ref.secretId, ref.jsonKey));
            }

            const value = secretCache.get(cacheKey);

            if (value === undefined) {
                unresolved.push(`${ref.name} (${ref.secretId})`);
                continue;
            }

            secretsByStack.set(stack, { ...secretsByStack.get(stack), [ref.name]: value });
        }

        // ⛔ THE SAME PROBLEM ONE INTRINSIC OVER. `valueForStringParameter` puts the NAME in `Environment`
        // but the value only at deploy, and `localImages.ts` handled that by OMITTING `CLERK_JWT_KEY` on the
        // stated grounds that "the schemas make these optional off deployed stages". recipe-service REQUIRES
        // it and refused to boot. These are PUBLIC verification keys and routing config that exist in SSM, so
        // they are read rather than omitted.
        //
        // ⚠️ A missing parameter is EXPECTED, not an error: the queue URLs resolve under `/kitchensink/dev/`,
        // a stage nobody deploys. Those fall through to the local placeholder as before.
        for (const ref of ssmRefsOf(JSON.parse(readFileSync(file, 'utf8')))) {
            const cacheKey = `ssm:${ref.parameterPath}`;

            if (!secretCache.has(cacheKey)) {
                secretCache.set(cacheKey, fetchSsmParameter(ref.parameterPath));
            }

            const value = secretCache.get(cacheKey);

            const local = ssmLocally[ref.parameterPath];

            if (value === undefined && local === undefined) {
                unresolved.push(`${ref.name} (${ref.parameterPath})`);
                continue;
            }

            if (value === undefined) {
                secretsByStack.set(stack, { ...secretsByStack.get(stack), [ref.name]: local as string });
                continue;
            }

            secretsByStack.set(stack, { ...secretsByStack.get(stack), [ref.name]: value });
        }
    }

    // ── Build OUR images, then point the local stack at them ────────────────────────────────────────
    //
    // ⛔ The CDK names the repository (`ContainerImage.fromEcrRepository`) but cannot say how to build it —
    // every asset manifest carries `dockerImages: []`. The rest is read from the repo: the package that
    // synthesised the stack owns the Dockerfile, and its own `docker:prepare` is what CI runs first.
    const imageBuilds = outcomes.flatMap((outcome) =>
        outcome.templates.flatMap((file) => [
            ...discoverImageBuilds(
                path.basename(file).replace(/\.template\.json$/u, ''),
                JSON.parse(readFileSync(file, 'utf8')),
                outcome.app,
            ),
        ]),
    );
    const uniqueBuilds = [...new Map(imageBuilds.map((build) => [build.localImage, build])).values()];
    const serviceContainers: ServiceContainer[] = [];
    const siblings: Record<string, number> = {};

    for (const build of uniqueBuilds) {
        const name = build.repository.replace(/^kitchensink-/u, '');
        const hostPort = localPortFor(build.dockerfile.replace(/\/Dockerfile$/u, ''));

        if (hostPort !== undefined) {
            siblings[name] = hostPort;
        }
    }

    if (process.env['LOCAL_SANDBOX_SKIP_BUILD'] === '1') {
        process.stdout.write('\n  images           : SKIPPED (LOCAL_SANDBOX_SKIP_BUILD=1)\n');
    } else {
        process.stdout.write(
            `\nBuilding ${String(uniqueBuilds.length)} service image(s) — compile, docker:prepare, docker build…\n`,
        );
    }

    for (const build of uniqueBuilds) {
        const name = build.repository.replace(/^kitchensink-/u, '');
        const hostPort = localPortFor(build.dockerfile.replace(/\/Dockerfile$/u, '')) ?? build.containerPort ?? 3000;
        // The stack's own database — the same resolution the migrations use.
        const stackTemplate = templates.find((file) => path.basename(file).startsWith(build.stack));
        const stackDbs =
            stackTemplate === undefined
                ? []
                : discoverDatabases([JSON.parse(readFileSync(stackTemplate, 'utf8'))], exportMap);
        const envKeys = tasksByStack.get(build.stack) ?? [];

        if (process.env['LOCAL_SANDBOX_SKIP_BUILD'] !== '1') {
            const built = buildServiceImage(build);

            if (!built.ok) {
                process.stderr.write(
                    `\n  image build FAILED for ${build.packageName}\n${built.output
                        .split('\n')
                        .slice(-12)
                        .map((l) => `      ${l}`)
                        .join('\n')}\n`,
                );
                process.exitCode = 1;

                return;
            }

            process.stdout.write(`  built ${build.localImage}\n`);
        }

        serviceContainers.push({
            name,
            image: build.localImage,
            hostPort,
            containerPort: build.containerPort ?? 3000,
            // ⚠️ Handed to `localContainerEnv` rather than spread around it, because the precedence is not a
            // simple "one side wins": local infrastructure must beat a resolved value (`DB_PASSWORD` names
            // the deployed RDS credential, and the local database is the postgres container), while a
            // resolved value must beat both the placeholder and the omission list. That ordering lives in one
            // place, with the rest of the env rules.
            environment: localContainerEnv(envKeys, {
                database: stackDbs[0] ?? 'postgres',
                port: build.containerPort ?? 3000,
                siblings,
                resolved: { ...importsByStack.get(build.stack), ...secretsByStack.get(build.stack) },
            }),
        });
    }

    const plan = planCompose(requirements, { databases, serviceContainers });

    mkdirSync(GENERATED_DIR, { recursive: true });
    writeFileSync(path.join(GENERATED_DIR, 'docker-compose.yml'), toYaml(plan));
    writeFileSync(path.join(GENERATED_DIR, 'init.sql'), plan.initSql);

    process.stdout.write(`\n  resources        : ${resources.length} across ${templates.length} template(s)\n`);
    process.stdout.write(`  LocalStack       : ${requirements.localstackServices.join(',')}\n`);
    process.stdout.write(`  databases        : ${databases.join(', ') || '(none declared)'}\n`);
    process.stdout.write(`  migrations owed  : ${requirements.migrations.length} (ADR-0022 — before services start)\n`);
    process.stdout.write(
        `  secrets resolved : ${String([...secretCache.values()].filter((v) => v !== undefined).length)} from Secrets Manager` +
            `${unresolved.length > 0 ? ` — UNRESOLVED: ${[...new Set(unresolved)].join(', ')}` : ''}\n`,
    );
    process.stdout.write(`  generated        : .local-sandbox/docker-compose.yml\n\n`);

    // Pre-flight, before docker gets a chance to fail obscurely several minutes into the run.
    const listening = spawnSync('ss', ['-lntH'], { encoding: 'utf8' });
    const inUse = [...(listening.stdout ?? '').matchAll(/:(\d+)\s/gu)].flatMap((m) =>
        m[1] === undefined ? [] : [Number(m[1])],
    );
    // Ports this project's own containers already publish — see `portConflicts`.
    const ownPublished = [
        ...(
            spawnSync('docker', ['ps', '--filter', 'name=local-sandbox-', '--format', '{{.Ports}}'], {
                encoding: 'utf8',
            }).stdout ?? ''
        ).matchAll(/:(\d+)->/gu),
    ].flatMap((match) => (match[1] === undefined ? [] : [Number(match[1])]));
    const clashes = portConflicts(serviceContainers, inUse, ownPublished);

    if (clashes.length > 0) {
        process.stderr.write('\nRefusing to start: host port(s) already in use.\n');

        for (const clash of clashes) {
            process.stderr.write(
                `  ${clash.name} wants :${String(clash.hostPort)} — free it, or stop whatever is listening.\n`,
            );
        }

        process.stderr.write(
            "  (the port comes from that service's own PORT default; recipe-service defaults to 3000, which Next.js also uses)\n",
        );
        process.exitCode = 1;

        return;
    }

    process.stdout.write('Starting containers…\n');
    const composeArgs = ['compose', '-f', path.join(GENERATED_DIR, 'docker-compose.yml'), '-p', 'local-sandbox'];
    const up = spawnSync('docker', [...composeArgs, 'up', '-d', '--wait'], { cwd: GENERATED_DIR, stdio: 'inherit' });

    if (up.status !== 0) {
        process.stderr.write('\ndocker compose up failed.\n');
        process.exitCode = up.status ?? 1;

        return;
    }

    // ── Populate LocalStack ─────────────────────────────────────────────────────────────────────────
    //
    // ⚠️ The endpoint here is the HOST one; the containers reach the same emulator as `localstack:4566`
    // over the compose network, which is what the resolved env already carries.
    const createdCounts = new Map<string, number>();
    const createFailures: string[] = [];

    for (const resource of toCreate) {
        const created = createLocalResource(resource, 'http://localhost:4566');

        if (created.ok) {
            createdCounts.set(resource.type, (createdCounts.get(resource.type) ?? 0) + 1);
            continue;
        }

        createFailures.push(`${resource.type} ${resource.name}: ${created.output.split('\n')[0] ?? ''}`);
    }

    const createdSummary = [...createdCounts.entries()]
        .map(([type, count]) => `${type.replace('AWS::', '')}×${String(count)}`)
        .sort()
        .join(' ');

    process.stdout.write(`\n  localstack       : ${createdSummary || '(nothing to create)'}\n`);

    // ⛔ Reported, never swallowed. A resource that failed to create is the difference between a stack that
    // works and one that 500s on the first upload, and the whole reason this step exists is that the absence
    // was previously INVISIBLE.
    for (const failure of createFailures) {
        process.stdout.write(`  · not created    : ${failure}\n`);
    }

    // ── ADR-0022's obligation, discharged ───────────────────────────────────────────────────────────
    //
    // ⛔ BEFORE any service starts, and that ordering is the whole point. `cdk deploy` returns only once ECS
    // has stabilised, so "deploy then migrate" served the new image against the OLD schema for the entire
    // stabilisation window — which is why the Trigger exists and why every service in the stack takes a
    // DependsOn against it. Locally there is no deploy to order against; applying the SQL here, before the
    // dev processes are told to start, is the same guarantee.
    //
    // The SQL is not named anywhere in this package: `Code.S3Key` gives the asset hash and CDK unpacked the
    // bundle beside its own template.
    let applied = 0;
    const skipped: string[] = [];

    for (const outcome of outcomes) {
        for (const file of outcome.templates) {
            const stack = path.basename(file).replace(/\.template\.json$/u, '');
            const parsed: unknown = JSON.parse(readFileSync(file, 'utf8'));
            const sets = discoverMigrations(stack, parsed);

            if (sets.length === 0) {
                continue;
            }

            // Which database? The stack's own templates name it concretely at STAGE=dev. Ambiguity is
            // reported rather than guessed — applying one service's schema to another's database is a worse
            // outcome than an unmigrated database, because it looks like it worked.
            const stackDatabases = discoverDatabases([parsed], exportMap);

            if (stackDatabases.length !== 1) {
                // ⚠️ Reported, but not alarming by default. Three shapes land here and only one is a gap:
                //   - a stack that owns NO database (ingredient-parser, ADR-0025 §3 — deliberate);
                //   - a stack that SHARES one its owning service already migrated (identity-webhooks,
                //     recipe-workers — ADR-0022 gives every DB-touching stack a runner, so the same ordered
                //     SQL is applied once by the owner and nothing is lost);
                //   - a name this tool genuinely could not resolve, which IS a gap.
                // They are not distinguished automatically because doing so would need a rule about which
                // stacks share whose database — a list, and the wrong kind of knowledge to put here.
                skipped.push(
                    `${stack} — names ${String(stackDatabases.length)} resolvable database(s); nothing applied. Fine if it owns none or shares one already migrated above.`,
                );
                continue;
            }

            const database = stackDatabases[0] as string;

            for (const set of sets) {
                const sqlDir = path.join(outcome.outDir, `asset.${set.assetHash}`, 'migrations');

                if (!existsSync(sqlDir)) {
                    continue;
                }

                // ⛔ RECORD WHAT IS APPLIED, the way ADR-0022's deployed runner does. `local:down` keeps the
                // postgres volume, so without this the second `local:up` re-applies file 0000 to a database
                // that already has the schema and dies on `type "food_status" already exists`.
                const psql = (
                    sqlText: string | undefined,
                    args: readonly string[],
                ): { status: number | null; stdout: string; stderr: string } => {
                    const result = spawnSync(
                        'docker',
                        ['exec', '-i', 'local-sandbox-postgres', 'psql', '-U', 'postgres', '-d', database, ...args],
                        sqlText === undefined
                            ? { encoding: 'utf8' as const }
                            : { input: sqlText, encoding: 'utf8' as const },
                    );

                    return { status: result.status, stdout: result.stdout ?? '', stderr: result.stderr ?? '' };
                };

                psql(undefined, [
                    '-v',
                    'ON_ERROR_STOP=1',
                    '-c',
                    `CREATE TABLE IF NOT EXISTS ${MIGRATION_TABLE} (name text PRIMARY KEY, applied_at timestamptz NOT NULL DEFAULT now())`,
                ]);

                const recorded = psql(undefined, ['-tAc', `SELECT name FROM ${MIGRATION_TABLE}`])
                    .stdout.split('\n')
                    .map((line: string) => line.trim())
                    .filter((line: string) => line !== '');

                // Filename order IS the migration order (`0000_`, `0001_`, …) — the same rule the deployed
                // runner uses, and the reason there is no hardcoded list of files.
                const owed = pendingMigrations(
                    readdirSync(sqlDir)
                        .filter((f) => f.endsWith('.sql'))
                        .sort(),
                    recorded,
                );

                for (const sql of owed) {
                    const run = spawnSync(
                        'docker',
                        [
                            'exec',
                            '-i',
                            'local-sandbox-postgres',
                            'psql',
                            '-v',
                            'ON_ERROR_STOP=1',
                            '-U',
                            'postgres',
                            '-d',
                            database,
                        ],
                        { input: readFileSync(path.join(sqlDir, sql), 'utf8'), encoding: 'utf8' },
                    );

                    if (run.status !== 0) {
                        process.stderr.write(`  migration FAILED ${database} ${sql}\n${run.stderr ?? ''}\n`);
                        process.exitCode = 1;

                        return;
                    }

                    // ⚠️ Recorded only AFTER the file succeeded — a failed migration must stay pending, or
                    // the next run would skip it and leave the schema permanently half-applied.
                    const record = psql(undefined, [
                        '-v',
                        'ON_ERROR_STOP=1',
                        '-c',
                        `INSERT INTO ${MIGRATION_TABLE} (name) VALUES ('${sql}') ON CONFLICT DO NOTHING`,
                    ]);

                    if (record.status !== 0) {
                        process.stderr.write(
                            `  could not record migration ${database} ${sql}\n${record.stderr ?? ''}\n`,
                        );
                        process.exitCode = 1;

                        return;
                    }

                    applied += 1;
                }

                process.stdout.write(`  migrated ${database} (${set.stack})\n`);
            }
        }
    }

    process.stdout.write(`\n  migrations applied : ${applied} file(s)\n`);

    for (const note of skipped) {
        process.stdout.write(`  · not migrated     : ${note}\n`);
    }

    // ── Our own services ────────────────────────────────────────────────────────────────────────────
    const tasks = outcomes.flatMap((outcome) =>
        outcome.templates.flatMap((file) => [
            ...discoverServiceTasks(
                path.basename(file).replace(/\.template\.json$/u, ''),
                JSON.parse(readFileSync(file, 'utf8')),
            ),
        ]),
    );

    process.stdout.write(`\n  services declared  : ${tasks.length}\n`);

    for (const task of tasks) {
        process.stdout.write(
            `      ${task.stack}/${task.logicalId}${task.containerPort === undefined ? ' (worker — no inbound port)' : ` :${String(task.containerPort)}`}\n`,
        );
    }

    process.stdout.write('\nUp. What is NOT covered:\n');

    for (const entry of requirements.unsupported) {
        process.stdout.write(`  ${entry.type} — ${entry.why}\n`);
    }

    // ⚠️ `turbo run dev` rather than something invented here: the repo ALREADY starts every service that
    // way (`dev:local`), each package's own `dev` script binds the port its own env schema defaults to
    // (identity 3001, food 3002, recipe 3000), and `.env.development` already wires the cross-service URLs
    // to those numbers. A port map invented in this package would be a second, competing convention.
    //
    // ⛔ NOT started from inside this command. `turbo run dev` is a watch process that never returns, and an
    // `up` that never returns cannot be composed or scripted. `npm run local:dev` chains the two.
    process.stdout.write(
        '\n  Services run as PROCESSES locally, not images — the CDK references prebuilt ECR tags\n' +
            '  (`ContainerImage.fromEcrRepository`), so it does not describe how to build them; CI does.\n' +
            '\n  Start them:  npm run dev:local        (or `npm run local:dev` to do both in one step)\n' +
            '  Stop this:   npm run local:down\n',
    );
}

await main();
