/**
 * `npm run local:up` — stand up every piece of infrastructure this repo declares, locally.
 *
 * ⛔ EVERYTHING HERE IS DERIVED FROM `cdk synth`. Nothing about which services, which containers, which
 * databases or which buckets is written down in this package. That is the whole point: a queue, bucket,
 * table or database added to the CDK tomorrow is stood up by this command the same day, with nothing to
 * remember and nothing to edit outside the CDK.
 *
 * It replaces two hand-maintained compose files that had already drifted apart and could not both run —
 * `docker-compose.yml` (LocalStack 3, `SERVICES: s3`) and `infra/localstack/docker-compose.yml`
 * (LocalStack 4.4.0, everything except s3). Both bind 5432 and 4566.
 *
 * @sideEffect Spawns CDK and docker, writes generated files under `.local-sandbox/`, and starts containers.
 */
import { spawnSync } from 'node:child_process';
import { mkdirSync, mkdtempSync, readFileSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import path from 'node:path';

import { discoverApps } from '../src/discoverApps.js';
import { discoverResources, summarizeRequirements, type DiscoveredResource } from '../src/discoverResources.js';
import { planCompose } from '../src/composePlan.js';
import { synthesizeAll } from '../src/synthesize.js';
import { REPO_ROOT, readManifests, runCdkSynth } from './adapters.js';

const GENERATED_DIR = path.join(REPO_ROOT, '.local-sandbox');

/**
 * Every logical database the synthesised CDK names.
 *
 * ⛔ DERIVED, not listed. Read from the RDS resource's own `DBName` and from any container environment
 * entry whose key names a database — which is where per-service and per-PR database names actually live
 * (ADR-0006). A hardcoded list here would be the same rot one layer down: `docker-compose.yml` created
 * exactly one database called `commise`, and the E2E harness created exactly one called `food_e2e`, so
 * neither could run the other's service.
 */
function discoverDatabases(templates: readonly string[]): readonly string[] {
    const names = new Set<string>();
    const looksLikeDatabaseKey = /(^|_)(DB_NAME|DATABASE_NAME|POSTGRES_DB)$/u;

    for (const file of templates) {
        const walk = (node: unknown): void => {
            if (Array.isArray(node)) {
                node.forEach(walk);

                return;
            }

            if (node === null || typeof node !== 'object') {
                return;
            }

            for (const [key, value] of Object.entries(node as Record<string, unknown>)) {
                if (key === 'DBName' && typeof value === 'string' && value.length > 0) {
                    names.add(value);
                }

                // A task definition's `Environment: [{ Name, Value }]`.
                if (key === 'Name' && typeof value === 'string' && looksLikeDatabaseKey.test(value)) {
                    const sibling = (node as { Value?: unknown }).Value;

                    if (typeof sibling === 'string' && /^[a-z_][a-z0-9_]*$/iu.test(sibling)) {
                        names.add(sibling);
                    }
                }

                walk(value);
            }
        };

        walk(JSON.parse(readFileSync(file, 'utf8')));
    }

    return [...names].sort();
}

/** Serialise the plan as compose YAML. Hand-rolled because the shape is small, fixed and fully ours. */
function toYaml(plan: ReturnType<typeof planCompose>): string {
    const lines = [
        '# GENERATED by `npm run local:up` from the synthesised CDK. Do not edit — regenerate.',
        '',
        'services:',
    ];

    for (const [name, service] of Object.entries(plan.services)) {
        if (service === undefined) {
            continue;
        }

        lines.push(
            `    ${name}:`,
            `        image: ${service.image}`,
            `        container_name: local-sandbox-${name}`,
            '        restart: unless-stopped',
            '        ports:',
            ...service.ports.map((port) => `            - '${port}'`),
            '        environment:',
            ...Object.entries(service.environment).map(([key, value]) => `            ${key}: '${value}'`),
            '        healthcheck:',
            `            test: ${JSON.stringify((service.healthcheck as { test: string[] }).test)}`,
            `            interval: ${String((service.healthcheck as { interval: string }).interval)}`,
            `            timeout: ${String((service.healthcheck as { timeout: string }).timeout)}`,
            `            retries: ${String((service.healthcheck as { retries: number }).retries)}`,
        );

        if (service.volumes !== undefined) {
            lines.push('        volumes:', ...service.volumes.map((volume) => `            - ${volume}`));
        }

        if (name === 'postgres') {
            lines.push('            - ./init.sql:/docker-entrypoint-initdb.d/init.sql:ro');
        }
    }

    lines.push('', 'volumes:', '    local-sandbox-pgdata:', '');

    return lines.join('\n');
}

async function main(): Promise<void> {
    const apps = discoverApps(readManifests());

    process.stdout.write(`Synthesising ${apps.length} CDK app(s) — this is the only source of truth…\n`);

    const outcomes = await synthesizeAll(apps, runCdkSynth, {
        outRoot: mkdtempSync(path.join(tmpdir(), 'local-sandbox-')),
    });
    const broken = outcomes.filter((outcome) => !outcome.usable);

    // ⛔ A hole in the inventory is indistinguishable from "that infrastructure does not exist", which is
    // exactly how the predecessor reported a repo with no database. Refuse rather than start something
    // partial and call it "everything".
    if (broken.length > 0) {
        process.stderr.write('\nRefusing to start: these apps did not synthesise, so the inventory is INCOMPLETE.\n');

        for (const outcome of broken) {
            process.stderr.write(
                `  ${outcome.app.packageName}\n${outcome.stderr
                    .trim()
                    .split('\n')
                    .slice(-4)
                    .map((l) => `      ${l}`)
                    .join('\n')}\n`,
            );
        }

        process.exitCode = 1;

        return;
    }

    const templates = outcomes.flatMap((outcome) => outcome.templates);
    const resources: DiscoveredResource[] = templates.flatMap((file) => [
        ...discoverResources(
            path.basename(file).replace(/\.template\.json$/u, ''),
            JSON.parse(readFileSync(file, 'utf8')),
        ),
    ]);
    const requirements = summarizeRequirements(resources);

    if (requirements.undecided.length > 0) {
        process.stderr.write('\nRefusing to start: infrastructure with no local-support decision.\n');

        for (const type of requirements.undecided) {
            process.stderr.write(`  ${type}\n`);
        }

        process.stderr.write('Add each to LOCAL_SUPPORT in src/localSupport.ts, with a reason.\n');
        process.exitCode = 1;

        return;
    }

    const databases = discoverDatabases(templates);
    const plan = planCompose(requirements, { databases });

    mkdirSync(GENERATED_DIR, { recursive: true });
    writeFileSync(path.join(GENERATED_DIR, 'docker-compose.yml'), toYaml(plan));
    writeFileSync(path.join(GENERATED_DIR, 'init.sql'), plan.initSql);

    process.stdout.write(`\n  resources        : ${resources.length} across ${templates.length} template(s)\n`);
    process.stdout.write(`  LocalStack       : ${requirements.localstackServices.join(',')}\n`);
    process.stdout.write(`  databases        : ${databases.join(', ') || '(none declared)'}\n`);
    process.stdout.write(`  migrations owed  : ${requirements.migrations.length} (ADR-0022 — before services start)\n`);
    process.stdout.write(`  generated        : .local-sandbox/docker-compose.yml\n\n`);

    process.stdout.write('Starting containers…\n');
    const composeArgs = ['compose', '-f', path.join(GENERATED_DIR, 'docker-compose.yml'), '-p', 'local-sandbox'];
    const up = spawnSync('docker', [...composeArgs, 'up', '-d', '--wait'], { cwd: GENERATED_DIR, stdio: 'inherit' });

    if (up.status !== 0) {
        process.stderr.write('\ndocker compose up failed.\n');
        process.exitCode = up.status ?? 1;

        return;
    }

    process.stdout.write('\nUp. What is NOT covered:\n');

    for (const entry of requirements.unsupported) {
        process.stdout.write(`  ${entry.type} — ${entry.why}\n`);
    }

    process.stdout.write(
        `\n  ${requirements.services.length} of our own services are declared in the CDK; start them with their own dev scripts\n` +
            '  (they are processes, not images, in local development — see docs/CODING_STANDARDS and each package).\n' +
            `\n  Stop with: docker compose -f .local-sandbox/docker-compose.yml -p local-sandbox down\n`,
    );
}

await main();
